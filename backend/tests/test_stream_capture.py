from .test_jobs import COURSE, FakeStt, FakeTum, _wait


class _Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *args):  # noqa: D401 - silence test output
        pass


@pytest.fixture(scope="module")
def hls_server(tmp_path_factory, sample_mp4):
    root = tmp_path_factory.mktemp("hls")
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-loglevel",
            "error",
            "-i",
            str(sample_mp4),
            "-c",
            "copy",
            "-f",
            "hls",
            "-hls_time",
            "2",
            "-hls_playlist_type",
            "vod",
            str(root / "playlist.m3u8"),
        ],
        check=True,
    )
    server = ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(_Quiet, directory=str(root)))
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    yield f"http://127.0.0.1:{server.server_port}/playlist.m3u8"
    server.shutdown()


@needs_ffmpeg
async def test_hls_duration_sums_extinf(hls_server):
    d = await hls_duration(hls_server)
    assert d is not None and 7.5 <= d <= 8.5


async def test_hls_duration_rejects_drm(tmp_path):
    import httpx

    body = '#EXTM3U\n#EXT-X-KEY:METHOD=SAMPLE-AES,URI="skd://x",KEYFORMAT="com.apple.streamingkeydelivery"\n#EXTINF:2,\na.ts\n'
    transport = httpx.MockTransport(lambda r: httpx.Response(200, text=body))
    with pytest.raises(DownloadError, match="DRM"):
        await hls_duration("https://edge/x.m3u8", transport=transport)


@needs_ffmpeg
async def test_ytdlp_records_stream_with_progress(hls_server, tmp_path):
    seen: list[Progress] = []
    dest = tmp_path / "rec.capture.mp4"
    size = await ytdlp_hls_download(hls_server, dest, seen.append, fragments=2)
    assert size > 10_000 and dest.exists()
    assert not list(tmp_path.glob("*.part")) and not list(tmp_path.glob("*.ytdl"))
    from lecture_studio.downloads.engine import probe

    info = await probe(dest)
    assert info.has_audio and info.has_video and 7.5 <= info.duration <= 8.5


def _stream_only_rec(url: str) -> Recording:
    return Recording(
        id=777,
        course_id=1,
        name="Rechnerarchitektur VL 1",
        description="",
        start="2026-11-02T11:00:00Z",
        end=None,
        duration=8,
        recording=True,
        live_now=False,
        is_planned=False,
        is_coming_up=False,
        playlists={"COMB": url},
        downloads=[],
    )


@needs_ffmpeg
async def test_capture_is_opt_in(settings, hls_server):
    db = Database(settings.db_path)
    rec = _stream_only_rec(hls_server)
    mgr = JobManager(db, EventBus(), settings, FakeTum(rec), FakeStt())
    res = mgr.enqueue_download(
        course=COURSE, recording=rec.to_public(), variant="COMB", auto_transcribe=False
    )
    job = await _wait(db, res["job"]["id"])
    assert job["status"] == "failed" and "Record streams" in job["error"]
    db.close()


@needs_ffmpeg
@pytest.mark.parametrize("use_ytdlp", [True, False])
async def test_capture_job_records_and_verifies(settings, hls_server, monkeypatch, use_ytdlp):
    import lecture_studio.jobs as jobs_mod

    if not use_ytdlp:
        monkeypatch.setattr(jobs_mod, "_ytdlp_available", lambda: False)
    db = Database(settings.db_path)
    db.set_setting("download.stream_capture", True)
    rec = _stream_only_rec(hls_server)
    mgr = JobManager(db, EventBus(), settings, FakeTum(rec), FakeStt())
    res = mgr.enqueue_download(
        course=COURSE, recording=rec.to_public(), variant="COMB", auto_transcribe=False
    )
    job = await _wait(db, res["job"]["id"])
    assert job["status"] == "completed", (job["error"], job["message"])
    assert "recorded from stream" in job["message"]
    out = Path(job["output_path"])
    assert out.name.endswith("[COMB] #777.mp4") and out.exists()
    assert not list(out.parent.glob("*.capture.*"))
    assert db.get_recording(777, "COMB")["size"] == out.stat().st_size
    db.close()


def test_words_roundtrip_and_edit_clears_them(settings):
    db = Database(settings.db_path)
    segs = [Segment(0.0, 1.0, "Hallo Welt", [Word(0.0, 0.4, " Hallo"), Word(0.5, 1.0, " Welt")])]
    tid = tstore.save(
        db,
        settings.transcripts_dir,
        transcript_id="w1",
        stream_id=1,
        variant="COMB",
        course_name="ERA",
        title="VL",
        media_path="/x",
        engine="fake",
        model="m",
        language="de",
        audio_seconds=1,
        processing_seconds=0.1,
        segments=segs,
        folder="f",
    )
    t = tstore.get(db, tid)
    assert t["segments"][0]["words"] == [[0.0, 0.4, " Hallo"], [0.5, 1.0, " Welt"]]
    t = tstore.update_segments(db, settings.transcripts_dir, tid, [{"idx": 0, "text": "Hallo, Welt!"}])
    assert t["segments"][0]["words"] is None and t["segments"][0]["text"] == "Hallo, Welt!"
    db.close()


def test_migration_adds_words_column(tmp_path):
    import sqlite3

    path = tmp_path / "old.db"
    con = sqlite3.connect(path)
    con.execute("CREATE TABLE segments (transcript_id TEXT, idx INTEGER, start REAL, end REAL, text TEXT)")
    con.commit()
    con.close()
    db = Database(path)
    cols = {r["name"] for r in db.query("PRAGMA table_info(segments)")}
    assert "words" in cols
    db.close()
